package jp.co.sample.kintai.payroll.domain;

/**
 * 給与連携から社員を除いた理由（BR-18）。
 *
 * <p><strong>除外はその月の給与が出ないことを意味する</strong>（労基法 24 条は毎月一定期日払いを定める）。
 * 一括締めと違い、支払期日を過ぎたら取り返せない。
 * 「除いた」だけでは人事が何をすればよいか分からないので、理由で分ける。
 */
public enum ExclusionReason {

    /** 打刻はあるが下書きのまま。本人に提出を促す */
    NOT_SUBMITTED,

    /** 提出済み・未承認。承認者に承認を促す */
    NOT_APPROVED,

    /** 承認済み・未締め。人事が締める */
    NOT_CLOSED,

    /**
     * 提出の事前条件を満たしていない（未退勤の勤務日がある・就業規則が未適用）。
     *
     * <p><strong>一般の未提出と分ける。</strong>
     * 本人が提出しようとしても拒否されるので、
     * 「本人に提出を促す」という<strong>実行できない案内</strong>になる。
     */
    NOT_SUBMITTABLE,

    /**
     * その月の打刻が 1 件も無い。休業か打刻漏れかを確かめる。
     *
     * <p><strong>月次勤怠の行の有無で判定しない。</strong>
     * 行は提出のときに初めて作られるので、行が無いことは「下書き」を意味する。
     * 行で判定すると、1 か月まるまる働いて提出していないだけの社員が
     * 「1 日も打刻が無い」と扱われる（CLAUDE.md 落とし穴 120）。
     */
    NO_ATTENDANCE_RECORD,

    /**
     * 同じ社員番号の社員が対象月に 2 人いる。
     *
     * <p>社員番号の一意制約は在籍者だけを見る部分一意インデックスなので、
     * <strong>退職者の番号は再利用できる。</strong>
     * 月中退職と同月の入社が重なると、給与側が別人を同一人物として名寄せする
     * （落とし穴 121）。<strong>2 人とも除外し、人事に割り当て直させる。</strong>
     */
    DUPLICATE_EMPLOYEE_NUMBER
}
